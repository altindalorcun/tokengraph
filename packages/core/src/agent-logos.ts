/**
 * Brand artwork for the agents token-graph reads, as 24x24 structured data (never raw SVG markup).
 * The Claude and Gemini marks are the colour variants from Lobe Icons (MIT), fills and gradients
 * unchanged. Codex CLI (OpenAI), Cursor, Cline and OpenCode have no colour mark, so they are
 * monochrome path data from Simple Icons (CC0) painted with the `ink` paint: callers resolve it to
 * the surrounding text colour (black on light, white on dark), as the brands' own guidance for
 * mono marks. The marks themselves are trademarks of their owners and are used only to identify
 * the tools token-graph reads. The app's `AgentLogo` and the README embed's legend both read this
 * one table, keyed by source id; a source without a mark has no entry.
 */

/** A fill: a literal colour, `ink` (the caller's foreground), or `url(#<gradient id>)`. */
export interface BrandLogoPath {
  d: string;
  fill: string;
  /** Draw with the even-odd fill rule (the default is nonzero). */
  evenodd?: boolean;
}

export interface BrandLogoStop {
  color: string;
  offset?: string;
  opacity?: string;
}

/** A linearGradient; `attrs` are its SVG attributes (x1, y1, x2, y2, gradientUnits, ...). */
export interface BrandLogoGradient {
  id: string;
  attrs: Record<string, string>;
  stops: BrandLogoStop[];
}

export interface BrandLogoArt {
  paths: BrandLogoPath[];
  gradients?: BrandLogoGradient[];
}

/**
 * Resolves a path's fill for one rendered instance. `ink` becomes `ink`; a gradient reference gets
 * `idPrefix` so several logos on one page (or in one SVG) never share a gradient id.
 */
export function brandPaint(fill: string, idPrefix: string, ink: string): string {
  if (fill === 'ink') return ink;
  const ref = /^url\(#(.+)\)$/.exec(fill);
  return ref ? `url(#${idPrefix}${ref[1]})` : fill;
}

