/**
 * Where the wordmark's lowercase body sits in the path's own coordinates: the top of the round
 * letters (o, e, n) and the baseline. The eye centres lowercase text on this band, not on the
 * ascenders and descenders.
 */
const WORDMARK_X_HEIGHT_TOP = 18.5;
const WORDMARK_BASELINE = 33.15;

/**
 * The flame is a drop: a narrow tip on top and its weight in the wide rows below, so the middle of
 * its bounding box reads as too high. The wordmark is lined up with the flame's visual centre
 * instead (the mean of its cell centres), which moves it down by about two units.
 */
function flameCentroidY(): number {
  return LOGO_CELLS.reduce((sum, [, y]) => sum + y + LOGO_CELL / 2, 0) / LOGO_CELLS.length;
}

export const LOGO_WORDMARK_SHIFT_Y =
  Math.round((flameCentroidY() - (WORDMARK_X_HEIGHT_TOP + WORDMARK_BASELINE) / 2) * 100) / 100;

/** Applied to the wordmark path wherever it is drawn next to the flame. */
export const LOGO_WORDMARK_TRANSFORM = `translate(0 ${LOGO_WORDMARK_SHIFT_Y})`;

