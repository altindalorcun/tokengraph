export type LogoTheme = 'light' | 'dark';
const SURFACE: Record<LogoTheme, { page: string; ink: string }> = {
  light: { page: '#f1f2ef', ink: '#121412' },
  dark: { page: '#0c0a09', ink: '#f5f5f4' },
};

export function logoCellMarkup(): string {
  return LOGO_CELLS.map(
    ([x, y, colour]) =>
      `<rect x="${x}" y="${y}" width="${LOGO_CELL}" height="${LOGO_CELL}" rx="${LOGO_RADIUS}" fill="${LOGO_PALETTE[colour]}"/>`,
  ).join('');
}

const head = (viewBox: string) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" role="img" aria-labelledby="t"><title id="t">tokengraph</title>`;

/** The flame alone: favicon, avatars, anywhere the wordmark does not fit. */
export function logoIconSvg(): string {
  return `${head(LOGO_ICON_VIEWBOX)}${logoCellMarkup()}</svg>\n`;
}

/** Flame plus wordmark, for a light or a dark surface. */
export function logoLockupSvg(theme: LogoTheme): string {
  return `${head(LOGO_LOCKUP_VIEWBOX)}${logoCellMarkup()}<path d="${LOGO_WORDMARK_PATH}" transform="${LOGO_WORDMARK_TRANSFORM}" fill="${SURFACE[theme].ink}"/></svg>\n`;
}

/** Bounds of the flame, used to centre it exactly in the app icon tile. */
function flameBounds() {
  const xs = LOGO_CELLS.map(([x]) => x);
  const ys = LOGO_CELLS.map(([, y]) => y);
  const x0 = Math.min(...xs);
  const y0 = Math.min(...ys);
  const x1 = Math.max(...xs) + LOGO_CELL;
  const y1 = Math.max(...ys) + LOGO_CELL;
  return { cx: (x0 + x1) / 2, cy: (y0 + y1) / 2, height: y1 - y0 };
}

/** 120-unit rounded tile with the flame centred exactly, 66 units tall. */
export function logoAppSvg(theme: LogoTheme): string {
  const { cx, cy, height } = flameBounds();
  const scale = 66 / height;
  const r = (v: number) => Math.round(v * 100) / 100;
  const transform = `translate(${r(60 - cx * scale)} ${r(60 - cy * scale)}) scale(${Math.round(scale * 10000) / 10000})`;
  return `${head('0 0 120 120')}<rect width="120" height="120" rx="27" fill="${SURFACE[theme].page}"/><g transform="${transform}">${logoCellMarkup()}</g></svg>\n`;
}
